const fs=require('fs');
const path=require('path');
const {getVersionNotes,meaningfulReleaseNotes,collectUpdateNotes}=require('../lib/releaseChangelog');
const markdown=fs.readFileSync(path.join(__dirname,'..','CHANGELOG.md'),'utf8');
const compare=(a,b)=>{
 const va=String(a).replace(/^v/,'').split('.').map(Number);
 const vb=String(b).replace(/^v/,'').split('.').map(Number);
 for(let i=0;i<3;i++)if(va[i]!==vb[i])return Math.sign(va[i]-vb[i]);
 return 0;
};

test('extracts actual per-version change entries, not a compare link',()=>{
 const notes=getVersionNotes(markdown,'v6.1.36');
 expect(notes).toContain('Media tab thumbnail grid');
 expect(notes).toContain('original splash GIF');
 expect(notes).not.toContain('Full Changelog');
 expect(getVersionNotes(markdown,'6.1.35')).toContain('operator notification center');
 expect(getVersionNotes(markdown,'v0.0.0')).toBe('');
});

test('detects GitHub autogenerated link-only notes as non-substantive',()=>{
 expect(meaningfulReleaseNotes('**Full Changelog**: https://github.com/Jacqueb-1337/liturgia-2/compare/v6.1.35...v6.1.36')).toBe(false);
 expect(meaningfulReleaseNotes('## What changed\n\n**Full Changelog**: https://github.com/org/repo/compare/a...b')).toBe(false);
 expect(meaningfulReleaseNotes('Release v6.1.36 - see git log for changes')).toBe(false);
 expect(meaningfulReleaseNotes('## What changed in v6.1.36\n- fix: resolve an updater problem')).toBe(true);
});

test('uses CHANGELOG.md when GitHub has only a comparison URL',()=>{
 const releases=[{tag_name:'v6.1.36',body:'**Full Changelog**: https://github.com/org/repo/compare/a...b'},
                 {tag_name:'v6.1.35',body:'**Full Changelog**: https://github.com/org/repo/compare/c...d'}];
 const results=collectUpdateNotes({releases,current:'6.1.34',latest:'v6.1.36',changelogMarkdown:markdown,compareVersions:compare});
 expect(results.map(r=>r.version)).toEqual(['v6.1.36','v6.1.35']);
 expect(results[0].body).toContain('Media tab thumbnail grid');
 expect(results[1].body).toContain('operator notification center');
 expect(results.every(r=>meaningfulReleaseNotes(r.body))).toBe(true);
});

test('keeps authored GitHub release notes and fills version gaps from changelog',()=>{
 const releases=[{tag_name:'v6.1.36',body:'- fix: my manually written fix'}];
 const results=collectUpdateNotes({releases,current:'6.1.34',latest:'v6.1.36',changelogMarkdown:markdown,compareVersions:compare});
 expect(results.map(r=>r.version)).toEqual(['v6.1.36','v6.1.35']);
 expect(results[0].body).toBe('- fix: my manually written fix');
});

test('never presents old installed release notes as part of newer update',()=>{
 const release=[{tag_name:'v6.1.36',body:''},{tag_name:'v6.1.35',body:''}];
 const results=collectUpdateNotes({releases:release,current:'6.1.35',latest:'6.1.36',changelogMarkdown:markdown,compareVersions:compare});
 expect(results.map(r=>r.version)).toEqual(['v6.1.36']);
});

test('future publishing workflow sources its notes from CHANGELOG.md instead of --generate-notes',()=>{
 const workflow=fs.readFileSync(path.join(__dirname,'..','.github/workflows/push-release.yml'),'utf8');
 const publisher=fs.readFileSync(path.join(__dirname,'..','scripts/prepare-release-notes.js'),'utf8');
 expect(workflow).toContain('node scripts/prepare-release-notes.js "$TAG" "$NOTES_FILE"');
 expect(workflow).toContain('gh release create "$TAG" --notes-file "$NOTES_FILE"');
 expect(workflow).not.toContain('gh release create "$TAG" --generate-notes');
 expect(publisher).toContain("getVersionNotes(markdown, tag)");
});
